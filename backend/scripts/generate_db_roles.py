"""Generate scripts/setup_db_roles.sql from config/roles.yaml.

Usage: python backend/scripts/generate_db_roles.py
Apply: backend/scripts/apply_db_roles.sh

Each app role gets its own read-only Postgres login with SELECT on exactly its
tables. Restricted columns are left out with column-level grants, so Postgres
rejects them even if the SQL validator is bypassed. Passwords are not in the
file; apply_db_roles.sh passes them in as psql variables from .env.

Write actions get separate writer logins (app/actions) with only the INSERT/UPDATE
grants their fixed SQL needs; the read-only logins above never get write access.
LOCAL DB ONLY: never run this against the shared source database.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.actions import ACTIONS  # noqa: E402
from app.db.models import Base  # noqa: E402
from app.security.roles import load_roles  # noqa: E402

OUT = Path(__file__).with_name("setup_db_roles.sql")


def role_sql(db_role: str, tables: list[str], excluded: dict[str, frozenset[str]]) -> list[str]:
    full = [t for t in tables if t not in excluded]
    lines = [
        f"-- {db_role}",
        f"ALTER ROLE {db_role} WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS",
        f"  PASSWORD :'{db_role}_password';",
        f"ALTER ROLE {db_role} SET default_transaction_read_only = on;",
        f"ALTER ROLE {db_role} SET statement_timeout = '5s';",
        f"REVOKE ALL ON ALL TABLES IN SCHEMA public FROM {db_role};",
        f"GRANT USAGE ON SCHEMA public TO {db_role};",
        f"GRANT SELECT ON {', '.join(full)} TO {db_role};",
    ]
    for table in sorted(excluded):
        cols = [c.name for c in Base.metadata.tables[table].columns if c.name not in excluded[table]]
        lines.append(f"GRANT SELECT ({', '.join(cols)}) ON {table} TO {db_role};  -- hides {', '.join(sorted(excluded[table]))}")
    return lines + [""]


def writer_sql(db_role: str, grants: list[str]) -> list[str]:
    return [
        f"-- {db_role} (write action login)",
        f"ALTER ROLE {db_role} WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS",
        f"  PASSWORD :'{db_role}_password';",
        f"ALTER ROLE {db_role} SET statement_timeout = '5s';",
        f"REVOKE ALL ON ALL TABLES IN SCHEMA public FROM {db_role};",
        f"GRANT USAGE ON SCHEMA public TO {db_role};",
        *[g.format(role=db_role) + ";" for g in grants],
        "",
    ]


def main() -> None:
    roles = load_roles().values()
    writers = {a.writer: a.module.GRANTS for a in ACTIONS.values()}
    names = ", ".join(f"'{r}'" for r in [*(r.db_role for r in roles), *writers])
    lines = [
        "-- Generated by backend/scripts/generate_db_roles.py from backend/config/roles.yaml. Do not edit.",
        "-- Apply with backend/scripts/apply_db_roles.sh (LOCAL DB ONLY).",
        "\\set ON_ERROR_STOP on",
        "BEGIN;",
        "",
        "DO $$",
        "DECLARE r text;",
        "BEGIN",
        f"  FOREACH r IN ARRAY ARRAY[{names}] LOOP",
        "    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = r) THEN",
        "      EXECUTE format('CREATE ROLE %I', r);",
        "    END IF;",
        "  END LOOP;",
        "END $$;",
        "",
        "REVOKE CREATE ON SCHEMA public FROM PUBLIC;",
        "",
    ]
    for role in roles:
        lines += role_sql(role.db_role, sorted(role.allowed_tables), role.excluded_columns)
    for writer, grants in writers.items():
        lines += writer_sql(writer, grants)
    lines.append("COMMIT;")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
