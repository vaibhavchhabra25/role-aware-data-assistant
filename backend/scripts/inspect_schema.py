"""Document the source schema: columns, keys, constraints, row counts (sample rows only with --samples).

Usage: python backend/scripts/inspect_schema.py  ->  docs/schema.md
"""

import sys

from psycopg import Connection, sql

from source_db import DOCS_DIR, SOURCE_TABLES, connect

# Sample rows are raw company records: opt in with --samples, keep them out of shared docs.
SAMPLE_ROWS = 3 if "--samples" in sys.argv else 0
MAX_CELL = 60

COLUMNS_SQL = """
SELECT column_name,
       CASE WHEN data_type = 'USER-DEFINED' THEN udt_name ELSE data_type END,
       is_nullable = 'YES',
       column_default
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = %s
ORDER BY ordinal_position
"""

CONSTRAINTS_SQL = """
SELECT contype, pg_get_constraintdef(oid)
FROM pg_constraint
WHERE conrelid = %s::regclass AND contype IN ('p', 'f', 'u', 'c')
ORDER BY contype DESC, conname
"""

CONSTRAINT_LABELS = {"p": "Primary key", "f": "Foreign key", "u": "Unique", "c": "Check"}


def cell(value: object) -> str:
    if value is None:
        return "NULL"
    text = str(value).replace("|", "\\|").replace("\n", " ")
    return text if len(text) <= MAX_CELL else text[: MAX_CELL - 1] + "…"


def md_table(headers: list[str], rows: list[list[object]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return lines


def describe_table(conn: Connection, table: str) -> list[str]:
    ident = sql.Identifier(table)
    columns = conn.execute(COLUMNS_SQL, (table,)).fetchall()
    constraints = conn.execute(CONSTRAINTS_SQL, (table,)).fetchall()
    row_count = conn.execute(sql.SQL("SELECT count(*) FROM {}").format(ident)).fetchone()[0]

    out = [f"## {table}", "", f"Rows: **{row_count}**", ""]
    out += md_table(
        ["Column", "Type", "Nullable", "Default"],
        [[name, typ, "yes" if nullable else "no", default or ""] for name, typ, nullable, default in columns],
    )
    if constraints:
        out += ["", "Constraints:", ""]
        out += [f"- {CONSTRAINT_LABELS[kind]}: `{definition}`" for kind, definition in constraints]
    if SAMPLE_ROWS:
        sample = conn.execute(sql.SQL("SELECT * FROM {} LIMIT {}").format(ident, sql.Literal(SAMPLE_ROWS)))
        out += ["", f"Sample ({SAMPLE_ROWS} rows):", ""]
        out += md_table([d.name for d in sample.description], [list(r) for r in sample.fetchall()])
    return out + [""]


def main() -> None:
    lines = [
        "# Source schema",
        "",
        "Generated by `backend/scripts/inspect_schema.py` from the company-provided DB (read-only).",
        f"Covers the {len(SOURCE_TABLES)} original tables in `public`; objects added by other users are ignored.",
        "",
    ]
    with connect() as conn:
        for table in SOURCE_TABLES:
            lines += describe_table(conn, table)

    DOCS_DIR.mkdir(exist_ok=True)
    (DOCS_DIR / "schema.md").write_text("\n".join(lines))
    print(f"Wrote {DOCS_DIR / 'schema.md'}")


if __name__ == "__main__":
    main()
